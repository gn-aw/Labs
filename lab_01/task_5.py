"""
Программа для учета числа запусков, а также их длительности.
Также программа собирает данные о коэфиценте и вычисляет квадрат его модуля.
"""
print("Введите имя исследователя")
name = input(str)
print("Введите название эксперимента")
name_exp = input(str)
print("Введите количество выполненных запусков")
cnt = int(input())
print("Введите длительность одного запуска (сек)")
time = int(input())
print("Введите действительную часть комплексного числа, затем мнимую часть")
r = int(input())
i = int(input())
ftime_sec = float(cnt * time)
ftime_min = float((cnt * time) / 60)
k = complex(r, i)
sq_abs = float(r ** 2 + i ** 2)
has_runs = bool(cnt)
print("========================================")
print(f"ЭКСПЕРИМЕНТ: {name_exp}")
print(f"Исследователь: {name}")
print(f"Запуски: {cnt}")
print(f"Общее время: {ftime_sec:.2f} с ({ftime_min:.2f} мин)")
print(f"Коэфицент: {k}")
print(f"Квадрат модуля: {sq_abs:.2f}")
print(f"Есть выполненные запуски: {has_runs}")
print("========================================")
print(f"Диагностическая строка: ИС:{type(name)} НЭ: {type(name_exp)} КЗ: {type(cnt)} Д3: {type(time)} ДЧ: {type(r)} МЧ: {type(i)}")